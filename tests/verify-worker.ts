import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { unzipSync, strFromU8 } from 'fflate';

const origin = 'http://127.0.0.1:4173';
const password = readFileSync('.env', 'utf8').match(/^ADMIN_PASSWORD=(.+)$/m)?.[1].trim();
assert(password && password.length >= 16);
const post = (path: string, value: unknown, headers = {}) => fetch(origin + path, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(value) });
const input = { requestId: randomUUID(), side: 'bride', name: '배포 런타임 검증', phone: '01000000000', attendance: 'yes', count: 2, companions: '', meal: 'no', bus: 'none', message: '=1+1', consent: true };
assert.equal((await fetch(origin + '/api/health')).status, 200);
assert.equal((await fetch(origin + '/api/admin/overview')).status, 401);
assert.equal((await post('/api/rsvp', input, { Origin: 'https://other.example' })).status, 403);
assert.equal((await post('/api/rsvp', { ...input, count: 1.5 })).status, 400);
assert.equal((await post('/api/rsvp', input)).status, 201);
assert.equal((await post('/api/rsvp', input)).status, 200);
assert.equal((await post('/api/rsvp', { ...input, count: 3 })).status, 409);
const login = await post('/api/admin/login', { password });
assert.equal(login.status, 200);
const cookie = login.headers.get('set-cookie')!.split(';')[0];
const overview = await (await fetch(origin + '/api/admin/overview', { headers: { Cookie: cookie } })).json();
assert(overview.rsvps.some((row: { requestId: string }) => row.requestId === input.requestId));
const excel = await fetch(origin + '/api/admin/rsvp.xlsx', { headers: { Cookie: cookie } });
assert.equal(excel.status, 200);
const archive = unzipSync(new Uint8Array(await excel.arrayBuffer()));
const xml = Object.entries(archive).filter(([name]) => name.endsWith('.xml')).map(([, bytes]) => strFromU8(bytes)).join('\n');
assert.match(xml, /배포 런타임 검증/); assert.match(xml, /01000000000/); assert.doesNotMatch(xml, /<f[ >]/);
assert.equal((await fetch(origin + '/api/snaps', { method: 'POST', headers: { Origin: origin } })).status, 403);
assert.equal((await post('/api/admin/logout', {}, { Cookie: cookie })).status, 200);
assert.equal((await fetch(origin + '/api/admin/overview', { headers: { Cookie: cookie } })).status, 401);
const html = await (await fetch(origin)).text();
assert.match(html, /현범과 주영/); assert.match(html, /http:\/\/127\.0\.0\.1:4173\/images\/share-card.png/);
console.log('배포 런타임 검증 통과: D1 저장·재시도·인증·엑셀·개시일·실제 페이지');
